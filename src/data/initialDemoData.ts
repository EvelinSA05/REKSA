// Helper to construct KebutuhanItem shape for relations
function makeKebutuhanItem(c: CaseRecord): KebutuhanItem {
  return {
    id: c.rawId || 1,
    kode_kasus: c.id,
    citizen_name: c.applicantName || "Andi Pratama",
    citizen_phone: c.applicantPhone || "+62 812 4455 0188",
    posko_id: 1,
    kategori_kebutuhan: c.item,
    volume_permintaan: c.qty,
    jumlah_kk: parseInt(c.kk?.replace(/\D/g, "") || "1") || 1,
    status_hunian: "Rumah Terdampak",
    tingkat_urgensi: c.urgency,
    status: c.status,
    deskripsi: c.conditionDescription,
    desa: c.village,
    kecamatan: c.district,
    kabupaten: c.regency,
    provinsi: c.province,
    latitude: c.lat,
    longitude: c.lng,
    total_alokasi_resmi: c.totalAlokasiResmi,
    total_diterima_resmi: c.totalDiterimaResmi,
  };
}

